local output_path = arg[1] or "FixedTables.inc"
local one = 1 << 20

local function round_half_up(value)
    return math.floor(value + 0.5)
end

local output = assert(io.open(output_path, "w"))
output:write("// Generated by FixedTables.gen.lua. Do not edit.\n")
output:write("static constexpr int32_t kSinDegTable[] = {\n")
for degree = 0, 360 do
    output:write(string.format("%d%s", round_half_up(math.sin(math.rad(degree)) * one), degree == 360 and "" or ","))
    output:write(degree % 12 == 11 and "\n" or " ")
end
output:write("\n};\n\n")

output:write("static constexpr int32_t kAtanDegTable[] = {\n")
for index = 0, 1024 do
    local ratio = index / 1024
    output:write(string.format("%d%s", round_half_up(math.deg(math.atan(ratio)) * one), index == 1024 and "" or ","))
    output:write(index % 12 == 11 and "\n" or " ")
end
output:write("\n};\n")
output:close()
